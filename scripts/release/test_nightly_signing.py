"""A train's nightly build is signed with the nightly key, which no release trusts (#1363).

Every key here is a throwaway one generated by the test; none is the
project's release or nightly key.
"""
import base64
import contextlib
import io
import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest import mock

import package
from package import (GUEST_METADATA, CHANNELS, guest_image_statement, package_release, trusted_keys,
                     verify_signature)

ROOT = Path(__file__).resolve().parents[2]
KEYS_RS = ROOT / "src" / "upgrade" / "keys.rs"


def generate_key(directory, name):
    """A fresh Ed25519 key: (PKCS#8 DER path, `ed25519:` public key)."""
    path = Path(directory) / f"{name}.der"
    subprocess.run(["openssl", "genpkey", "-algorithm", "ED25519", "-outform", "DER", "-out", str(path)],
                   check=True, capture_output=True)
    public = subprocess.run(["openssl", "pkey", "-inform", "DER", "-in", str(path), "-pubout", "-outform", "DER"],
                            check=True, capture_output=True).stdout
    return path, "ed25519:" + base64.b64encode(public[-32:]).decode()


def keys_source(release, nightly):
    """A keys.rs with these keys, laid out like the real one."""
    quoted = lambda keys: "".join(f'    "{key}",\n' for key in keys)
    return (f"pub const EMBEDDED_RELEASE_KEYS: &[&str] =\n    &[\n{quoted(release)}];\n\n"
            f"pub const NIGHTLY_SIGNING_KEYS: &[&str] = &[\n"
            f"    // NIGHTLY_PUBLIC_KEY: replace this comment\n{quoted(nightly)}];\n")


class KeyListTests(unittest.TestCase):
    def test_each_channel_reads_only_its_own_list(self):
        source = keys_source(["ed25519:" + "A" * 43 + "="], ["ed25519:" + "B" * 43 + "="])
        self.assertEqual(trusted_keys(source, "release"), ["ed25519:" + "A" * 43 + "="])
        self.assertEqual(trusted_keys(source, "nightly"), ["ed25519:" + "B" * 43 + "="])

    def test_the_placeholder_is_an_empty_nightly_list(self):
        self.assertEqual(trusted_keys(keys_source(["ed25519:" + "A" * 43 + "="], []), "nightly"), [])

    def test_the_real_lists_never_share_a_key(self):
        source = KEYS_RS.read_text()
        release, nightly = trusted_keys(source, "release"), trusted_keys(source, "nightly")
        self.assertTrue(release)
        self.assertFalse(set(release) & set(nightly))

    def test_the_real_release_list_is_the_one_the_release_build_compiles(self):
        # package.py used to read every quoted key in keys.rs; now that the
        # nightly list lives there too, it must read the release list alone.
        self.assertEqual(trusted_keys(KEYS_RS.read_text(), "release"),
                         ["ed25519:zSUgsFfmv0WohbjRJE7FJf/xgLIgMuK7AbnDgOdduRM="])

    def test_a_missing_list_is_an_error(self):
        with self.assertRaises(ValueError):
            trusted_keys("pub const SOMETHING_ELSE: &[&str] = &[];", "nightly")


class ChannelSigningTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.release_key, self.release_public = generate_key(self.root, "release")
        self.nightly_key, self.nightly_public = generate_key(self.root, "nightly")
        self.assets = self.root / "assets"
        self.assets.mkdir()
        for binary, platforms in package.PLATFORMS.items():
            for platform in platforms:
                (self.assets / f"{binary}-{platform}").write_bytes(f"test binary {binary}-{platform}".encode())
        self.pins = json.loads(Path(package.__file__).with_name("guest-images.json").read_text())
        for image in self.pins["images"].values():
            (self.assets / image["asset"]).write_bytes(b"test image: " + image["asset"].encode())

    def package(self, key, trusted, forbidden=()):
        package_release(self.assets, "v0.2.4", "reliaburger/reliaburger", key, trusted, self.pins,
                        forbidden_keys=forbidden)

    def test_a_nightly_signed_with_the_nightly_key_verifies_only_with_it(self):
        self.package(self.nightly_key, [self.nightly_public], forbidden=[self.release_public])
        metadata = json.loads((self.assets / GUEST_METADATA).read_text())
        for arch, image in metadata["images"].items():
            statement = guest_image_statement("v0.2.4", arch, image["asset"], image["sha256"],
                                              image["source"]["sha256"])
            self.assertTrue(verify_signature(self.nightly_public, statement, image["signature"]))
            # What a released relish holds: the release key. It refuses the nightly.
            self.assertFalse(verify_signature(self.release_public, statement, image["signature"]))
        envelope = json.loads((self.assets / "bun-linux-x86_64.sig").read_text())
        binary = (self.assets / "bun-linux-x86_64").read_bytes()
        self.assertTrue(verify_signature(self.nightly_public, binary, envelope["embedded"]))
        self.assertFalse(verify_signature(self.release_public, binary, envelope["embedded"]))

    def test_the_release_key_can_never_sign_a_nightly(self):
        # Even if someone added it to the nightly list, the release list forbids it.
        with self.assertRaises(ValueError) as caught:
            self.package(self.release_key, [self.release_public, self.nightly_public],
                         forbidden=[self.release_public])
        self.assertIn("other channel", str(caught.exception))
        self.assertFalse((self.assets / "metadata.json").exists())

    def test_the_nightly_key_cannot_sign_a_release(self):
        with self.assertRaises(ValueError):
            self.package(self.nightly_key, [self.release_public], forbidden=[self.nightly_public])
        self.assertFalse((self.assets / "metadata.json").exists())

    def test_an_empty_nightly_list_signs_nothing(self):
        with self.assertRaises(ValueError) as caught:
            self.package(self.nightly_key, [], forbidden=[self.release_public])
        self.assertIn("not trusted", str(caught.exception))

    def test_verify_signature_refuses_garbage(self):
        self.assertFalse(verify_signature(self.nightly_public, b"data", base64.b64encode(b"x" * 64).decode()))
        self.assertFalse(verify_signature(self.nightly_public, b"data", "not base64!"))
        self.assertFalse(verify_signature("ed25519:short", b"data", base64.b64encode(b"x" * 64).decode()))


class ChannelSecretTests(unittest.TestCase):
    """package.py reads the secret its channel names, and a nightly never sees the release key."""

    def run_main(self, arguments, environment):
        with mock.patch.dict(os.environ, environment, clear=True), \
                mock.patch.object(package, "package_release") as packaged, \
                contextlib.redirect_stderr(io.StringIO()):
            package.main(["--directory", "dist", "--version", "v0.2.4",
                          "--repository", "reliaburger/reliaburger", *arguments])
        return packaged

    def key_secret(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        path, _ = generate_key(temp.name, "throwaway")
        return base64.b64encode(path.read_bytes()).decode()

    def test_the_channels_are_release_and_nightly(self):
        self.assertEqual(set(CHANNELS), {"release", "nightly"})

    def test_a_nightly_reads_the_nightly_secret_and_the_nightly_list(self):
        packaged = self.run_main(["--channel", "nightly"], {"RELIABURGER_NIGHTLY_KEY": self.key_secret()})
        trusted, forbidden = packaged.call_args.args[4], packaged.call_args.kwargs["forbidden_keys"]
        source = KEYS_RS.read_text()
        self.assertEqual(trusted, trusted_keys(source, "nightly"))
        self.assertEqual(forbidden, trusted_keys(source, "release"))

    def test_a_release_reads_the_release_secret_and_the_release_list(self):
        packaged = self.run_main([], {"RELIABURGER_RELEASE_KEY": self.key_secret()})
        trusted, forbidden = packaged.call_args.args[4], packaged.call_args.kwargs["forbidden_keys"]
        source = KEYS_RS.read_text()
        self.assertEqual(trusted, trusted_keys(source, "release"))
        self.assertEqual(forbidden, trusted_keys(source, "nightly"))

    def test_a_nightly_refuses_to_run_where_the_release_key_is_present(self):
        with self.assertRaises(ValueError) as caught:
            self.run_main(["--channel", "nightly"], {"RELIABURGER_NIGHTLY_KEY": self.key_secret(),
                                                     "RELIABURGER_RELEASE_KEY": "anything"})
        self.assertIn("RELIABURGER_RELEASE_KEY", str(caught.exception))
        self.assertNotIn("anything", str(caught.exception))

    def test_a_nightly_without_its_secret_names_the_secret(self):
        with self.assertRaises(ValueError) as caught:
            self.run_main(["--channel", "nightly"], {})
        self.assertIn("RELIABURGER_NIGHTLY_KEY", str(caught.exception))


class BootstrapRefusesNightlyTests(unittest.TestCase):
    """The website's `install.sh` never installs a nightly unless qualification asks for one."""

    BOOTSTRAP = ROOT / "docs" / "website" / "install.sh"
    NIGHTLY = "https://github.com/reliaburger/reliaburger/releases/download/nightly-v0.2.4-123-1"

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        tools = self.root / "tools"
        tools.mkdir()
        # A curl that records every URL and serves an installer that only
        # says it ran, so nothing real is downloaded or installed.
        (tools / "curl").write_text("""#!/bin/sh
while [ "$#" -gt 0 ]; do
  case "$1" in
    -o) output=$2; shift ;;
    https://*) url=$1 ;;
  esac
  shift
done
printf '%s\\n' "$url" >> "$URLS"
printf 'echo installer ran\\n' > "$output"
""")
        (tools / "curl").chmod(0o755)
        self.urls = self.root / "urls"
        self.env = dict(os.environ, HOME=str(self.root), URLS=str(self.urls),
                        PATH=str(tools) + os.pathsep + os.environ["PATH"])
        self.env.pop("RELIABURGER_ACCEPT_NIGHTLY", None)

    def bootstrap(self, base_url, **extra):
        self.urls.unlink(missing_ok=True)
        return subprocess.run(["sh", str(self.BOOTSTRAP), "--install-only"], capture_output=True,
                              env=dict(self.env, RELIABURGER_RELEASE_BASE_URL=base_url, **extra))

    def test_a_nightly_mirror_is_refused_before_anything_is_downloaded(self):
        for url in (self.NIGHTLY, self.NIGHTLY + "/"):
            with self.subTest(url=url):
                result = self.bootstrap(url)
                self.assertNotEqual(result.returncode, 0)
                self.assertIn(b"nightly build", result.stderr)
                self.assertFalse(self.urls.exists(), "a refused nightly reached curl")

    def test_only_an_explicit_yes_lets_qualification_install_one(self):
        for value in ("", "0", "yes", "true"):
            with self.subTest(value=value):
                self.assertNotEqual(self.bootstrap(self.NIGHTLY, RELIABURGER_ACCEPT_NIGHTLY=value).returncode, 0)
        result = self.bootstrap(self.NIGHTLY, RELIABURGER_ACCEPT_NIGHTLY="1")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.urls.read_text().splitlines(), [self.NIGHTLY + "/install.sh"])

    def test_a_staging_mirror_still_installs(self):
        staging = "https://github.com/reliaburger/reliaburger/releases/download/staging-v0.2.4-123-1"
        result = self.bootstrap(staging)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.urls.read_text().splitlines(), [staging + "/install.sh"])

    def test_a_nightly_tag_is_not_a_version_either(self):
        self.urls.unlink(missing_ok=True)
        env = dict(self.env, RELIABURGER_VERSION="nightly-v0.2.4-123-1")
        result = subprocess.run(["sh", str(self.BOOTSTRAP), "--install-only"], capture_output=True, env=env)
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse(self.urls.exists())


if __name__ == "__main__":
    unittest.main()
